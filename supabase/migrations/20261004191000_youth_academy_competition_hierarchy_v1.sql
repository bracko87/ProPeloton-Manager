language plpgsql
security definer
set search_path=public,private,auth,pg_temp
as $function$
declare
  v_user uuid:=auth.uid();
  v_academy_id uuid;
  v_region text;
  v_season integer:=coalesce(public.get_current_season_number(),1);
  v_membership public.youth_academy_competition_memberships%rowtype;
begin
  if v_user is null then raise exception 'Not authenticated'; end if;

  select a.id,private.youth_region_for_country_v1(c.country_code)
  into v_academy_id,v_region
  from public.youth_academies a
  join public.clubs c on c.id=a.club_id
  where c.owner_user_id=v_user and c.deleted_at is null and a.is_active=true
  limit 1;

  if v_academy_id is null then
    return jsonb_build_object('activated',false);
  end if;

  perform public.ensure_youth_competition_memberships_v1(v_season);

  select * into v_membership
  from public.youth_academy_competition_memberships
  where season_number=v_season and academy_id=v_academy_id;

  return jsonb_build_object(
    'activated',true,
    'season_number',v_season,
    'region_code',v_region,
    'my_membership',jsonb_build_object(
      'competition_class',v_membership.competition_class,
      'division_code',v_membership.division_code
    ),
    'academy_divisions',(
      with rider_rows as (
        select
          rr.race_id,rr.academy_id,rr.finish_position,
          row_number() over(
            partition by rr.race_id,rr.academy_id
            order by rr.finish_position nulls last,rr.youth_rider_id
          ) rn
        from public.youth_race_results rr
        join public.youth_races r on r.id=rr.race_id
        where r.season_number=v_season and rr.result_status='finished'
      ),
      race_points as (
        select
          x.academy_id,
          sum(
            case r.competition_class
              when 'world' then private.youth_race_base_points_v1(x.finish_position)*2
              when 'continental' then round(
                private.youth_race_base_points_v1(x.finish_position)*1.25
              )::integer
              else private.youth_race_base_points_v1(x.finish_position)
            end
          )::bigint points,
          count(distinct x.race_id)::integer starts
        from rider_rows x
        join public.youth_races r on r.id=x.race_id
        where x.rn<=3
        group by x.academy_id
      ),
      standing_rows as (
        select
          m.competition_class,m.division_code,m.academy_id,c.name academy_name,
          c.country_code,
          coalesce(p.points,0)::bigint points,
          coalesce(p.starts,0)::integer starts,
          row_number() over(
            partition by m.competition_class,m.division_code
            order by coalesce(p.points,0) desc,
                     private.youth_academy_strength_v1(m.academy_id) desc,
                     lower(c.name),m.academy_id
          )::integer rank_no,
          count(*) over(
            partition by m.competition_class,m.division_code
          )::integer total_teams
        from public.youth_academy_competition_memberships m
        join public.youth_academies a on a.id=m.academy_id and a.is_active=true
        join public.clubs c on c.id=a.club_id
        left join race_points p on p.academy_id=m.academy_id
        where m.season_number=v_season
      ),
      divisions as (
        select
          s.competition_class,s.division_code,
          min(case
            when s.competition_class='world' then 1
            when s.competition_class='continental' and s.division_code='CONTINENTAL_WEST' then 2
            when s.competition_class='continental' then 3
            else 10
          end) sort_order,
          jsonb_agg(jsonb_build_object(
            'rank',s.rank_no,
            'academy_id',s.academy_id,
            'academy_name',s.academy_name,
            'country_code',s.country_code,
            'points',s.points,
            'starts',s.starts,
            'total_teams',s.total_teams,
            'is_mine',s.academy_id=v_academy_id,
            'promotion_zone',false,
            'relegation_zone',false
          ) order by s.rank_no) teams
        from standing_rows s
        group by s.competition_class,s.division_code
      )
      select coalesce(jsonb_agg(jsonb_build_object(
        'competition_class',d.competition_class,
        'division_code',d.division_code,
        'teams',d.teams
      ) order by d.sort_order,d.division_code),'[]'::jsonb)
      from divisions d
    ),
    'regional',(
      with totals as (
        select yr.id,yr.display_name,yr.country_code,yr.academy_id,
          sum(rr.regional_points)::bigint points,
          count(*) filter(where rr.result_status='finished')::integer starts
        from public.youth_riders yr
        join public.youth_race_results rr on rr.youth_rider_id=yr.id
        join public.youth_races r on r.id=rr.race_id
        join public.youth_academies ya on ya.id=yr.academy_id
        join public.clubs yc on yc.id=ya.club_id
        where r.season_number=v_season
          and private.youth_region_for_country_v1(yc.country_code)=v_region
        group by yr.id,yr.display_name,yr.country_code,yr.academy_id
      ),
      ranked as (
        select t.*,dense_rank() over(order by points desc,id)::integer rank_no
        from totals t
      )
      select coalesce(jsonb_agg(jsonb_build_object(
        'rank',x.rank_no,'rider_id',x.id,'rider_name',x.display_name,
        'country_code',x.country_code,'academy_id',x.academy_id,
        'academy_name',c.name,'points',x.points,'starts',x.starts,
        'is_mine',x.academy_id=v_academy_id
      ) order by x.rank_no),'[]'::jsonb)
      from (select * from ranked order by rank_no limit 100) x
      join public.youth_academies a on a.id=x.academy_id
      join public.clubs c on c.id=a.club_id
    ),
    'world',(
      with totals as (
        select yr.id,yr.display_name,yr.country_code,yr.academy_id,
          sum(rr.world_points)::bigint points,
          count(*) filter(where rr.result_status='finished')::integer starts
        from public.youth_riders yr
        join public.youth_race_results rr on rr.youth_rider_id=yr.id
        join public.youth_races r on r.id=rr.race_id
        where r.season_number=v_season
        group by yr.id,yr.display_name,yr.country_code,yr.academy_id
      ),
      ranked as (
        select t.*,dense_rank() over(order by points desc,id)::integer rank_no
        from totals t
      )
      select coalesce(jsonb_agg(jsonb_build_object(
        'rank',x.rank_no,'rider_id',x.id,'rider_name',x.display_name,
        'country_code',x.country_code,'academy_id',x.academy_id,
        'academy_name',c.name,'points',x.points,'starts',x.starts,
        'is_mine',x.academy_id=v_academy_id
      ) order by x.rank_no),'[]'::jsonb)
      from (select * from ranked order by rank_no limit 100) x
      join public.youth_academies a on a.id=x.academy_id
      join public.clubs c on c.id=a.club_id
    )
  );
end;
$function$;

revoke all on function public.get_my_youth_rankings_v1()
from public,anon;
grant execute on function public.get_my_youth_rankings_v1()
to authenticated;

delete from public.youth_races r
where r.metadata->>'calendar_source'='phase3'
  and r.status='scheduled'
  and not exists(
    select 1 from public.youth_race_entries e where e.race_id=r.id
  )
  and not exists(
    select 1 from public.youth_race_results rr where rr.race_id=r.id
  );

select public.ensure_youth_competition_memberships_v1(
  coalesce(public.get_current_season_number(),1)
);

select public.seed_youth_race_calendar_for_season_v1(
  coalesce(public.get_current_season_number(),1)
);

update public.youth_races
set status='cancelled',updated_at=now(),
    metadata=metadata||jsonb_build_object('prelaunch_cancelled',true)
where season_number=coalesce(public.get_current_season_number(),1)
  and metadata->>'calendar_source'='youth_hierarchy_v1'
  and race_date<=public.get_current_game_date_date()
  and status='scheduled';

update public.youth_race_invitations i
set status='expired',responded_on=public.get_current_game_date_date(),updated_at=now()
from public.youth_races r
where r.id=i.race_id and r.status='cancelled' and i.status='pending';

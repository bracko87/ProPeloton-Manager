            invitation_response_deadline=excluded.invitation_response_deadline,
            metadata=excluded.metadata,
            updated_at=now()
        returning id into v_race_id;

        insert into public.youth_race_invitations(
          race_id,academy_id,invitation_type,status,invited_on,response_deadline,
          priority_score,metadata
        )
        select
          v_race_id,x.academy_id,'continental_pool','pending',v_date-21,v_date-7,
          x.priority_score,
          jsonb_build_object('source','continental_weighted_pool')
        from (
          select
            a.id academy_id,
            (
              case
                when public.get_amateur_division_for_country(c.country_code)=v_host_regional
                  then 30 else 0
              end
              +case m.competition_class
                when 'continental' then 20 when 'world' then 16 else 10 end
              +private.youth_academy_strength_v1(a.id)*0.05
              +private.youth_deterministic_fraction_v1(
                v_race_id::text||a.id::text||'continental_invite'
              )*8
            )::numeric priority_score
          from public.youth_academies a
          join public.clubs c on c.id=a.club_id
          join public.youth_academy_competition_memberships m
            on m.academy_id=a.id and m.season_number=v_season
          where a.is_active=true
            and private.youth_continental_division_for_country_v1(c.country_code)=v_division
          order by priority_score desc,a.id
          limit 20
        ) x
        on conflict(race_id,academy_id) do nothing;

        v_inserted:=v_inserted+1;
      end loop;
    end loop;

    foreach v_division in array v_regional_divisions loop
      for v_slot in 1..6 loop
        v_day:=case v_slot
          when 1 then 2 when 2 then 6 when 3 then 10
          when 4 then 14 when 5 then 18 else 22 end;
        v_date:=public.game_date_from_parts(v_season,v_month,v_day);
        v_days:=1;
        v_end_date:=v_date;
        select city_name,country_code,division_code
        into v_city,v_country,v_host_regional
        from private.pick_youth_race_host_city_v1(
          v_division,v_season*30000+v_month*300+v_slot+
          array_position(v_regional_divisions,v_division)*10
        );
        v_region:=private.youth_region_for_country_v1(v_country);
        v_name:=private.youth_generated_race_name_v1('regional',v_city,v_slot);
        v_terrain:=(array['flat','hilly','mountain','mixed','time_trial'])
          [1+mod(v_month+v_slot+array_position(v_regional_divisions,v_division),5)];

        insert into public.youth_races(
          season_number,race_date,race_name,race_level,region_code,terrain_type,
          distance_km,entry_cost,lineup_size,qualification_rank_limit,status,
          competition_class,division_code,host_city,host_country_code,
          team_limit,race_days,race_end_date,invitation_response_deadline,metadata
        )
        values(
          v_season,v_date,v_name,'regional',v_region,v_terrain,
          42+v_slot*4+mod(v_month,4)*2,150+v_slot*10,5,null,'scheduled',
          'regional',v_division,v_city,v_country,16,1,v_end_date,v_date-5,
          jsonb_build_object(
            'calendar_source','youth_hierarchy_v1',
            'results_only',true,'replay_available',false,
            'host_regional_division',v_division
          )
        )
        on conflict(season_number,race_date,race_name) do update
        set competition_class=excluded.competition_class,
            division_code=excluded.division_code,
            host_city=excluded.host_city,
            host_country_code=excluded.host_country_code,
            team_limit=excluded.team_limit,
            race_days=excluded.race_days,
            race_end_date=excluded.race_end_date,
            invitation_response_deadline=excluded.invitation_response_deadline,
            metadata=excluded.metadata,
            updated_at=now()
        returning id into v_race_id;

        insert into public.youth_race_invitations(
          race_id,academy_id,invitation_type,status,invited_on,response_deadline,
          priority_score,metadata
        )
        select
          v_race_id,a.id,'regional_local','pending',v_date-18,v_date-5,
          50+private.youth_deterministic_fraction_v1(
            v_race_id::text||a.id::text||'regional_invite'
          )*5,
          jsonb_build_object('source','home_regional_division')
        from public.youth_academies a
        join public.clubs c on c.id=a.club_id
        where a.is_active=true
          and public.get_amateur_division_for_country(c.country_code)=v_division
        on conflict(race_id,academy_id) do nothing;

        v_inserted:=v_inserted+1;
      end loop;
    end loop;
  end loop;

  return jsonb_build_object(
    'season_number',v_season,
    'races_processed',v_inserted,
    'world_per_month',5,
    'continental_per_month',10,
    'regional_per_division_per_month',6,
    'results_only',true,
    'replay_available',false
  );
end;

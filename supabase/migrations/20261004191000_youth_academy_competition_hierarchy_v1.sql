create or replace function private.ensure_youth_monthly_race_plan_v1(
  p_academy_id uuid,
  p_season integer,
  p_month integer
)
returns void
language plpgsql
security definer
set search_path=public,private,pg_temp
as $function$
declare
  v_class text;
  v_is_ai boolean:=false;
begin
  select m.competition_class,a.is_ai
  into v_class,v_is_ai
  from public.youth_academy_competition_memberships m
  join public.youth_academies a on a.id=m.academy_id
  where m.season_number=p_season and m.academy_id=p_academy_id;

  if v_class is null then return; end if;

  insert into public.youth_monthly_race_plans(
    academy_id,season_number,month_number,
    world_race_limit,continental_race_limit,regional_race_limit,
    max_monthly_cost,approved,approved_at
  )
  values(
    p_academy_id,p_season,p_month,
    case v_class when 'world' then 3 when 'continental' then 1 else 0 end,
    case v_class when 'world' then 2 when 'continental' then 4 else 2 end,
    case v_class when 'world' then 2 when 'continental' then 3 else 5 end,
    case v_class when 'world' then 10000 when 'continental' then 7000 else 5000 end,
    v_is_ai,
    case when v_is_ai then now() else null end
  )
  on conflict(academy_id,season_number,month_number) do nothing;
end;
$function$;

create or replace function private.pick_youth_race_host_city_v1(
  p_scope text,
  p_seed integer
)
returns table(city_name text,country_code text,division_code text)
language sql
stable
set search_path=public,private,pg_temp
as $function$
  select h.city_name,h.country_code,h.division_code
  from public.youth_race_host_cities h
  where h.is_active=true
    and (
      p_scope='WORLD'
      or (
        p_scope='CONTINENTAL_WEST'
        and private.youth_continental_division_for_country_v1(h.country_code)='CONTINENTAL_WEST'
      )
      or (
        p_scope='CONTINENTAL_EAST'
        and private.youth_continental_division_for_country_v1(h.country_code)='CONTINENTAL_EAST'
      )
      or h.division_code=p_scope
    )
  order by md5(p_seed::text||':'||h.id::text)
  limit 1;
$function$;

create or replace function private.youth_generated_race_name_v1(
  p_class text,
  p_city text,
  p_slot integer
)
returns text
language sql
immutable
as $function$
  select case p_class
    when 'world' then case mod(p_slot-1,5)
      when 0 then 'Youth World Cup – '||p_city
      when 1 then p_city||' U16 Grand Prix'
      when 2 then 'Youth World Classic – '||p_city
      when 3 then p_city||' International Youth Trophy'
      else 'World Youth Challenge – '||p_city end
    when 'continental' then case mod(p_slot-1,5)
      when 0 then p_city||' Continental Youth Cup'
      when 1 then p_city||' U16 Classic'
      when 2 then 'Continental Youth Trophy – '||p_city
      when 3 then 'Grand Prix '||p_city||' U16'
      else p_city||' Youth Challenge' end
    else case mod(p_slot-1,6)
      when 0 then p_city||' Youth Cup'
      when 1 then 'Grand Prix '||p_city||' U16'
      when 2 then p_city||' Junior Trophy'
      when 3 then p_city||' Youth Classic'
      when 4 then 'Prize of '||p_city||' U16'
      else p_city||' Regional Challenge' end
  end;
$function$;

create or replace function public.seed_youth_race_calendar_for_season_v1(
  p_season integer default null
)
returns jsonb
language plpgsql
security definer
set search_path=public,private,pg_temp
as $function$
declare
  v_season integer:=coalesce(p_season,public.get_current_season_number(),1);
  v_month integer;
  v_slot integer;
  v_day integer;
  v_division text;
  v_city text;
  v_country text;
  v_host_regional text;
  v_region text;
  v_date date;
  v_end_date date;
  v_days integer;
  v_terrain text;
  v_name text;
  v_race_id uuid;
  v_inserted integer:=0;
  v_regional_divisions text[]:=array[
    'NORTH_AMERICA','SOUTH_AMERICA','WESTERN_EUROPE','CENTRAL_EUROPE',
    'SOUTHERN_BALKAN_EUROPE','NORTHERN_EASTERN_EUROPE',
    'WEST_NORTH_AFRICA','CENTRAL_SOUTH_AFRICA','WEST_CENTRAL_ASIA',
    'SOUTH_ASIA','EAST_SOUTHEAST_ASIA','OCEANIA'
  ];
begin
  perform public.ensure_youth_competition_memberships_v1(v_season);

  for v_month in 1..12 loop
    for v_slot in 1..5 loop
      v_day:=case v_slot when 1 then 4 when 2 then 9 when 3 then 14 when 4 then 19 else 24 end;
      v_date:=public.game_date_from_parts(v_season,v_month,v_day);
      v_days:=case
        when v_slot=2 and v_month in (6,9) then 6
        when v_slot=3 and v_month in (3,12) then 3
        else 1
      end;
      v_end_date:=v_date+(v_days-1);
      select city_name,country_code,division_code
      into v_city,v_country,v_host_regional
      from private.pick_youth_race_host_city_v1(
        'WORLD',v_season*10000+v_month*100+v_slot
      );
      v_name:=private.youth_generated_race_name_v1('world',v_city,v_slot);
      v_terrain:=(array['flat','hilly','mountain','mixed','time_trial'])
        [1+mod(v_month+v_slot,5)];

      insert into public.youth_races(
        season_number,race_date,race_name,race_level,region_code,terrain_type,
        distance_km,entry_cost,lineup_size,qualification_rank_limit,status,
        competition_class,division_code,host_city,host_country_code,
        team_limit,race_days,race_end_date,invitation_response_deadline,metadata
      )
      values(
        v_season,v_date,v_name,
        case when v_month=12 and v_slot=5 then 'world_final' else 'world_series' end,
        'world',v_terrain,
        least(120,72+v_days*7+v_slot*2),600+v_days*140,5,null,'scheduled',
        'world','WORLD',v_city,v_country,20,v_days,v_end_date,v_date-14,
        jsonb_build_object(
          'calendar_source','youth_hierarchy_v1',
          'results_only',true,'replay_available',false,
          'host_regional_division',v_host_regional
        )
      )
      on conflict(season_number,race_date,race_name) do update
      set competition_class=excluded.competition_class,
          division_code=excluded.division_code,
          host_city=excluded.host_city,
          host_country_code=excluded.host_country_code,
          team_limit=excluded.team_limit,
          race_days=excluded.race_days,
          race_end_date=excluded.race_end_date,
          invitation_response_deadline=excluded.invitation_response_deadline,
          metadata=excluded.metadata,
          updated_at=now()
      returning id into v_race_id;

      insert into public.youth_race_invitations(
        race_id,academy_id,invitation_type,status,invited_on,response_deadline,
        priority_score,metadata
      )
      select
        v_race_id,m.academy_id,'world_class','pending',v_date-28,v_date-14,
        1000-coalesce(m.seed_rank,999),
        jsonb_build_object('source','all_world_class')
      from public.youth_academy_competition_memberships m
      where m.season_number=v_season and m.competition_class='world'
      on conflict(race_id,academy_id) do nothing;

      v_inserted:=v_inserted+1;
    end loop;

    foreach v_division in array array['CONTINENTAL_WEST','CONTINENTAL_EAST'] loop
      for v_slot in 1..5 loop
        v_day:=case v_slot when 1 then 3 when 2 then 8 when 3 then 13 when 4 then 18 else 23 end;
        v_date:=public.game_date_from_parts(v_season,v_month,v_day);
        v_days:=case when v_slot=3 and v_month in (4,8) then 2 else 1 end;
        v_end_date:=v_date+(v_days-1);
        select city_name,country_code,division_code
        into v_city,v_country,v_host_regional
        from private.pick_youth_race_host_city_v1(
          v_division,
          v_season*20000+v_month*200+v_slot+
            case when v_division='CONTINENTAL_EAST' then 50 else 0 end
        );
        v_region:=private.youth_region_for_country_v1(v_country);
        v_name:=private.youth_generated_race_name_v1(
          'continental',v_city,
          v_slot+case when v_division='CONTINENTAL_EAST' then 5 else 0 end
        );
        v_terrain:=(array['flat','hilly','mountain','mixed','time_trial'])
          [1+mod(v_month+v_slot+
            case when v_division='CONTINENTAL_EAST' then 2 else 0 end,5)];

        insert into public.youth_races(
          season_number,race_date,race_name,race_level,region_code,terrain_type,
          distance_km,entry_cost,lineup_size,qualification_rank_limit,status,
          competition_class,division_code,host_city,host_country_code,
          team_limit,race_days,race_end_date,invitation_response_deadline,metadata
        )
        values(
          v_season,v_date,v_name,'regional',v_region,v_terrain,
          least(105,58+v_days*6+v_slot*2),350+v_days*90,5,null,'scheduled',
          'continental',v_division,v_city,v_country,20,v_days,v_end_date,v_date-7,
          jsonb_build_object(
            'calendar_source','youth_hierarchy_v1',
            'results_only',true,'replay_available',false,
            'host_regional_division',v_host_regional
          )
        )
        on conflict(season_number,race_date,race_name) do update
        set competition_class=excluded.competition_class,
            division_code=excluded.division_code,
            host_city=excluded.host_city,
            host_country_code=excluded.host_country_code,
            team_limit=excluded.team_limit,
            race_days=excluded.race_days,

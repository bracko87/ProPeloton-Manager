create or replace function private.youth_race_rider_eligible_v1(
  p_rider_id uuid,
  p_race_date date
)
returns boolean
language plpgsql
stable
security definer
set search_path=public,private,pg_temp
as $function$
declare
  v_rider public.youth_riders%rowtype;
  v_age integer;
  v_recent_starts integer;
begin
  select * into v_rider from public.youth_riders where id=p_rider_id;
  if v_rider.id is null or v_rider.status<>'academy' then return false; end if;

  v_age:=extract(year from age(p_race_date,v_rider.birth_date))::integer;
  if v_age<12 or v_age>16 then return false; end if;

  select count(distinct x.race_id)::integer
  into v_recent_starts
  from (
    select rr.race_id
    from public.youth_race_results rr
    join public.youth_races r on r.id=rr.race_id
    where rr.youth_rider_id=p_rider_id
      and rr.result_status in ('finished','dnf')
      and r.race_date>=p_race_date-30
      and r.race_date<p_race_date
    union
    select e.race_id
    from public.youth_race_lineups l
    join public.youth_race_entries e on e.id=l.entry_id
    join public.youth_races r on r.id=e.race_id
    where l.youth_rider_id=p_rider_id
      and e.status='entered'
      and r.race_date>=p_race_date-30
      and r.race_date<p_race_date
  ) x;

  return coalesce(v_recent_starts,0)<private.youth_race_monthly_start_limit_v1(v_age)
    and v_rider.fatigue<78
    and v_rider.readiness>=45;
end;
$function$;

create or replace function private.youth_rider_available_for_race_v1(
  p_rider_id uuid,
  p_race_id uuid
)
returns boolean
language plpgsql
stable
security definer
set search_path=public,private,pg_temp
as $function$
declare
  v_race public.youth_races%rowtype;
begin
  select * into v_race from public.youth_races where id=p_race_id;
  if v_race.id is null then return false; end if;

  if not private.youth_race_rider_eligible_v1(p_rider_id,v_race.race_date) then
    return false;
  end if;

  return not exists(
    select 1
    from public.youth_race_lineups l
    join public.youth_race_entries e on e.id=l.entry_id
    join public.youth_races other on other.id=e.race_id
    where l.youth_rider_id=p_rider_id
      and e.status='entered'
      and other.id<>p_race_id
      and daterange(
        other.race_date,coalesce(other.race_end_date,other.race_date),'[]'
      ) && daterange(
        v_race.race_date,coalesce(v_race.race_end_date,v_race.race_date),'[]'
      )
  );
end;
$function$;

create or replace function private.youth_race_academy_qualified_v1(

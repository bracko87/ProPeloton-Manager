
-- ProPeloton Manager historical city-weather V2 research storage.
-- RESEARCH ONLY: no changes to race_stages, weather cancellation functions,
-- results, gameplay clocks, public clients, or production simulation.
-- Coordinates / historical readings must NOT be invented or defaulted to country centres.

create table if not exists private.weather_v2_locations (
  location_id bigint generated by default as identity primary key,
  country_code text not null check (country_code ~ '^[A-Z]{2}$'),
  name text not null check (length(btrim(name)) > 0),
  name_key text generated always as (lower(regexp_replace(btrim(name), '[[:space:]]+', ' ', 'g'))) stored,
  latitude numeric(9,6) check (latitude between -90 and 90),
  longitude numeric(9,6) check (longitude between -180 and 180),
  elevation_m numeric(9,1),
  timezone_iana text,
  geocode_status text not null default 'unresolved'
    check (geocode_status in ('unresolved', 'ambiguous', 'verified', 'not_found')),
  -- A country inferred from the containing race is not proof of the city's country.
  country_from_race boolean not null default true,
  location_source text,
  source_url text,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (country_code, name_key),
  constraint verified_location_has_coordinates check (
    geocode_status <> 'verified' or
    (latitude is not null and longitude is not null and
     nullif(btrim(timezone_iana),'') is not null and
     nullif(btrim(location_source),'') is not null and
     verified_at is not null)
  ),
  constraint location_coordinates_together check (
    (latitude is null and longitude is null) or
    (latitude is not null and longitude is not null)
  )
);

create table if not exists private.weather_v2_season_reference_year (
  game_season integer primary key check (game_season >= 1),
  historical_year smallint not null check (historical_year between 2016 and 2025),
  mapping_version text not null default 'research_20261110_v1',
  created_at timestamptz not null default now()
);

-- Fixed global year per season: nearby cities stay in the same weather system.
-- Repeating this 10-year cycle after Season 10 requires a separately approved policy.
insert into private.weather_v2_season_reference_year (game_season, historical_year)
values (1,2025), (2,2020), (3,2023), (4,2018), (5,2022),
       (6,2017), (7,2024), (8,2019), (9,2021), (10,2016)
on conflict (game_season) do nothing;

-- Pure date mapping. Game year 2000 = S1, game year 2001 = S2.
-- Non-leap historical years map a Feb 29 stage to Feb 28 (explicitly flagged).
create or replace function private.weather_v2_reference_date(p_stage_date date)
returns table (
  game_season integer,
  historical_year smallint,
  historical_date date,
  date_mapping_note text
)
language sql stable
set search_path = private, pg_temp
as $function$
  select y.game_season, y.historical_year,
    case
      when extract(month from p_stage_date) = 2
       and extract(day from p_stage_date) = 29
       and not (y.historical_year % 400 = 0
                or (y.historical_year % 4 = 0 and y.historical_year % 100 <> 0))
      then make_date(y.historical_year::integer, 2, 28)
      else make_date(y.historical_year::integer,
                     extract(month from p_stage_date)::integer,
                     extract(day from p_stage_date)::integer)
    end,
    case
      when extract(month from p_stage_date) = 2
       and extract(day from p_stage_date) = 29
       and not (y.historical_year % 400 = 0
                or (y.historical_year % 4 = 0 and y.historical_year % 100 <> 0))
      then 'feb29_mapped_to_feb28'
      else 'same_month_day'
    end
  from private.weather_v2_season_reference_year y
  where p_stage_date is not null
    and y.game_season = extract(year from p_stage_date)::integer - 1999;
$function$;

-- Cached hourly reanalysis/observations for a *verified* coordinate.
-- A UTC key preserves the duplicated local hour during daylight-saving transitions.
-- Only import licensed, attributed archive data; never use a country-wide proxy.
create table if not exists private.weather_v2_hourly_archive (
  location_id bigint not null references private.weather_v2_locations(location_id),
  historical_utc timestamptz not null,
  historical_local_date date not null,
  historical_local_hour smallint not null check (historical_local_hour between 0 and 23),
  temperature_c numeric(7,2),
  relative_humidity_pct numeric(6,2) check (relative_humidity_pct between 0 and 100),
  precipitation_mm numeric(9,2) check (precipitation_mm >= 0),
  snowfall_cm numeric(9,2) check (snowfall_cm >= 0),
  wind_speed_kmh numeric(8,2) check (wind_speed_kmh >= 0),
  wind_gust_kmh numeric(8,2) check (wind_gust_kmh >= 0),
  wind_direction_deg numeric(6,2) check (wind_direction_deg >= 0 and wind_direction_deg <= 360),
  weather_code smallint,
  dataset text not null,
  dataset_version text not null,
  source_url text not null,
  source_license text not null,
  imported_at timestamptz not null default now(),
  primary key (location_id, historical_utc, dataset, dataset_version),
  constraint weather_hourly_has_value check (
    temperature_c is not null or precipitation_mm is not null or
    snowfall_cm is not null or wind_speed_kmh is not null or
    weather_code is not null
  )
);
create index if not exists weather_v2_hourly_by_local_day
  on private.weather_v2_hourly_archive(location_id, historical_local_date, historical_local_hour);

create table if not exists private.weather_v2_daily_archive (
  location_id bigint not null references private.weather_v2_locations(location_id),
  historical_date date not null,
  avg_temp_c numeric(7,2),
  min_temp_c numeric(7,2),
  max_temp_c numeric(7,2),
  precipitation_mm numeric(9,2) check (precipitation_mm >= 0),
  snowfall_cm numeric(9,2) check (snowfall_cm >= 0),
  max_wind_kmh numeric(8,2) check (max_wind_kmh >= 0),
  weather_code smallint,
  dataset text not null,
  dataset_version text not null,
  source_url text not null,
  source_license text not null,
  imported_at timestamptz not null default now(),
  primary key (location_id, historical_date, dataset, dataset_version),
  constraint weather_daily_has_value check (
    avg_temp_c is not null or min_temp_c is not null or
    max_temp_c is not null or precipitation_mm is not null or
    snowfall_cm is not null or weather_code is not null
  ),
  constraint weather_daily_temp_order check (
    min_temp_c is null or max_temp_c is null or min_temp_c <= max_temp_c
  )
);

-- Research-only per-stage proposed source: NOT consumed by production.
create table if not exists private.weather_v2_stage_candidate (
  stage_id uuid primary key references public.race_stages(id) on delete cascade,
  game_season integer not null references private.weather_v2_season_reference_year(game_season),
  historical_date date not null,
  start_location_id bigint references private.weather_v2_locations(location_id),
  finish_location_id bigint references private.weather_v2_locations(location_id),
  status text not null default 'unresolved' check (status in ('unresolved', 'in_review', 'validated')),
  candidate_snapshot jsonb,
  evidence jsonb,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint weather_candidate_validated_needs_evidence check (
    status <> 'validated' or
    (start_location_id is not null and finish_location_id is not null
     and candidate_snapshot is not null and evidence is not null and reviewed_at is not null)
  )
);

-- Seed raw names for a geo-verification queue. These are NEVER treated as verified.
-- Start, finish and named host locations belong to the race's country until checked.
insert into private.weather_v2_locations (country_code, name)
select distinct coalesce(nullif(upper(btrim(s.host_country_code)),''),upper(btrim(r.country_code))) as country_code,
       btrim(loc.city_name) as name
from public.race_stages s
join public.races r on r.id = s.race_id
cross join lateral (values (s.start_city), (s.finish_city), (s.host_city)) as loc(city_name)
where nullif(btrim(loc.city_name),'') is not null
  and coalesce(nullif(upper(btrim(s.host_country_code)),''),nullif(upper(btrim(r.country_code)),'')) ~ '^[A-Z]{2}$'
on conflict (country_code, name_key) do nothing;


import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const sql=readFileSync(new URL('./sql/v4_research_only_stage_source_lock.sql',import.meta.url),'utf8')
const noComments=sql.replace(/--[^\r\n]*/g,'')

test('only private research objects are created and no sporting object is modified',()=>{
 assert.match(sql,/CREATE TABLE IF NOT EXISTS private\.v4_research_locked_full_stage_sources_v1/)
 assert.match(sql,/ENABLE ROW LEVEL SECURITY/)
 assert.match(sql,/SECURITY INVOKER/)
 assert.match(sql,/REVOKE ALL ON FUNCTION private\.v4_capture_research_locked_stage_source_v1/)
 assert.match(sql,/FROM PUBLIC, anon, authenticated, service_role, v4_live_shadow_read_login/)
 assert.doesNotMatch(noComments,/\b(?:UPDATE|DELETE FROM|INSERT INTO|TRUNCATE)\s+(?:public|auth|storage|cron)\./i)
 assert.doesNotMatch(noComments,/cron\.schedule|net\.http_post|CREATE TRIGGER .* ON public\./i)
 assert.doesNotMatch(noComments,/ALTER TABLE public\.|DROP TABLE public\.|CREATE OR REPLACE FUNCTION public\./i)
})
test('requires a trusted transaction and never writes after stage start',()=>{
 assert.match(sql,/session_user <> 'postgres'/)
 assert.match(sql,/current_setting\('transaction_isolation'\) NOT IN \('repeatable read','serializable'\)/)
 assert.match(sql,/current_setting\('transaction_read_only'\) <> 'off'/)
 assert.match(sql,/v_now<v_cutoff/)
 assert.match(sql,/v_now>v_cutoff\+interval '15 minutes' OR v_now>=v_start/)
 assert.match(sql,/v_clock\.is_paused/)
 assert.match(sql,/V4_RESEARCH_COMPLETED_STAGE_FORBIDDEN/)
 assert.match(sql,/FROM public\.race_stage_simulation_runs/)
})
test('source is persistent, immutable, private and explicitly not official',()=>{
 assert.match(sql,/source_kind text NOT NULL DEFAULT 'v4_research_capture_not_official_production_lock'/)
 assert.match(sql,/BEFORE UPDATE OR DELETE ON private\.v4_research_locked_full_stage_sources_v1/)
 assert.match(sql,/INSERT INTO private\.v4_research_locked_full_stage_sources_v1/)
 assert.match(sql,/ON CONFLICT \(stage_id\) DO NOTHING/)
 assert.match(sql,/extensions\.digest\(convert_to\(v_payload::text,'UTF8'\),'sha256'\)/)
 assert.match(sql,/originalPlanStatusesPreserved',true/)
 assert.match(sql,/original_submitted_plan_count/)
 assert.match(sql,/production_source_parity_verified',false/)
 assert.doesNotMatch(noComments,/SET\s+status\s*=\s*'locked'/i)
})
test('capture snapshots only unambiguous road-stage source inputs',()=>{
 assert.match(sql,/v_stage\.stage_format <> 'road_race'/)
 assert.match(sql,/v_stage\.terrain_type NOT IN \('flat','hilly','mountain','cobbled'\)/)
 assert.match(sql,/V4_RESEARCH_COMPETITION_UNSUPPORTED/)
 assert.match(sql,/V4_RESEARCH_TEAM_OWNERSHIP_UNAVAILABLE/)
 assert.match(sql,/V4_RESEARCH_RIDER_COMMANDS_INCOMPLETE/)
 assert.match(sql,/V4_RESEARCH_HUMAN_PLAN_MISSING/)
 assert.match(sql,/jsonb_array_length\(v_commands\)<>v_riders_count/)
 assert.match(sql,/V4_RESEARCH_SOURCE_SIZE_REJECTED/)
 assert.doesNotMatch(noComments,/universal_race_stage_get_calculation_payload_v1\(/)
 assert.doesNotMatch(noComments,/universal_race_stage_force_mandatory_jersey_phase9_v1\(/)
})

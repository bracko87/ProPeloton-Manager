import assert from 'node:assert/strict'
import {calculatePackPowerV3,roadWattsRequiredV3} from '../../src/race-engine-v3/pelotonPowerBalanceV3.ts'
const rider=(id,tactic='follow',energy=.9)=>({riderId:id,sustainableWatts:300,energy,tactic,massKg:83})
const road={gradePercent:0,headwindMps:0,crosswindMps:0}
const solo=calculatePackPowerV3([rider('a')],road)
const group=calculatePackPowerV3(Array.from({length:12},(_,i)=>rider(String(i).padStart(2,'0'))),road)
assert(group.attainableSpeedMps>solo.attainableSpeedMps,'Draft must confer pack benefit')
const attack=calculatePackPowerV3([rider('a','attack'),...Array.from({length:11},(_,i)=>rider(String(i).padStart(2,'0')))],road)
assert(attack.attainableSpeedMps>group.attainableSpeedMps,'Attack contribution can move pack only with actual watts')
assert(attack.attainableSpeedMps<group.attainableSpeedMps*1.03,'One rider cannot add 30% to entire pack speed')
assert(attack.totalContributorWatts>0)
assert(attack.peakWorkerEnergyCostPerSecond>0)
const chase=calculatePackPowerV3([rider('a','chase'),...Array.from({length:11},(_,i)=>rider(String(i).padStart(2,'0')))],road)
assert(chase.totalContributorWatts>0)
assert(chase.attainableSpeedMps>group.attainableSpeedMps)
assert(chase.attainableSpeedMps<attack.attainableSpeedMps)
const depleted=calculatePackPowerV3([rider('a','attack',.06)],road)
assert.equal(depleted.totalContributorWatts,0,'Depleted riders cannot repeatedly burst')
assert(depleted.attainableSpeedMps<solo.attainableSpeedMps)
const hill=calculatePackPowerV3([rider('a')],{...road,gradePercent:8})
assert(hill.attainableSpeedMps<solo.attainableSpeedMps)
const wetCross=calculatePackPowerV3(Array.from({length:12},(_,i)=>rider(String(i).padStart(2,'0'))),{...road,crosswindMps:10})
assert(wetCross.attainableSpeedMps<group.attainableSpeedMps)
const head=calculatePackPowerV3([rider('a')],{...road,headwindMps:6})
const tail=calculatePackPowerV3([rider('a')],{...road,headwindMps:-6})
assert(head.attainableSpeedMps<solo.attainableSpeedMps&&tail.attainableSpeedMps>solo.attainableSpeedMps)
for(const delta of [.001,.01,.1]){
 const little=calculatePackPowerV3(Array.from({length:12},(_,i)=>rider(String(i).padStart(2,'0'))),{...road,crosswindMps:delta})
 assert(Math.abs(little.attainableSpeedMps-group.attainableSpeedMps)<.1,'Tiny wind change should not cause catastrophic velocity jump')
}
const reversed=calculatePackPowerV3(Array.from({length:12},(_,i)=>rider(String(i).padStart(2,'0'))).reverse(),road)
assert.deepEqual(reversed,group,'No input-order advantage')
assert(Math.abs(roadWattsRequiredV3(10,83,.36,road)-roadWattsRequiredV3(10,83,.36,road))<1e-9)
assert.throws(()=>calculatePackPowerV3([rider('a'),rider('a')],road))
assert.throws(()=>calculatePackPowerV3([rider('a','attack',1.1)],road))
assert.throws(()=>calculatePackPowerV3([rider('a')],{gradePercent:30}))
console.log('PASS pack power: aerodynamic drafting, worker watts, energy, 8% climb, wind, smooth input changes, deterministic order')
console.log(JSON.stringify({solo:solo.attainableSpeedMps,peloton:group.attainableSpeedMps,oneChaser:chase.attainableSpeedMps,oneAttacker:attack.attainableSpeedMps,climb:hill.attainableSpeedMps,wind:wetCross.attainableSpeedMps},null,2))

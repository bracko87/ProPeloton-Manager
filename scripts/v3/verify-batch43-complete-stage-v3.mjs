/** Batch 43 terminal line: chronological crossing, exact checkpoint and no writes. */
import assert from 'node:assert/strict'
import {initializeCoupled2DResearchV3,advanceCoupled2DResearchV3,summarizeCoupled2DResearchV3} from './coupled2DMicroV3.mjs'
import {BATCH40_GEOMETRIES} from './roadWidthLookaheadV3.mjs'
const make=(seed='a')=>({riders:Array.from({length:8},(_,i)=>({riderId:seed+'-'+i,meters:90-Math.floor(i/4)*2,lane:i%4,speedMps:9,cpWatts:200+i*5,wPrimeJoules:15000,tactic:i===0?'attack':'tempo'})),route:[{lengthKm:.1,gradePercent:0}],geometry:BATCH40_GEOMETRIES[1],allowSteering:true})
const input=make()
const initial=initializeCoupled2DResearchV3(input)
assert.equal(initial.complete,false)
assert.equal(initial.finish.length,0)
assert.equal(initial.input.finishDistanceMeters,100)
const completed=advanceCoupled2DResearchV3(initial,30)
assert.equal(completed.complete,true)
assert.equal(completed.finish.length,8)
assert.equal(completed.tick,1)
assert(completed.finish.every(x=>x.finishSeconds>0&&x.finishSeconds<=10))
assert.equal(completed.riders.filter(x=>x.finishSeconds!==null).length,8)
assert.deepEqual(advanceCoupled2DResearchV3(completed,1),completed,'Completed race changed after finish')
let checkpoint=structuredClone(initial)
checkpoint=JSON.parse(JSON.stringify(advanceCoupled2DResearchV3(checkpoint,1)))
assert.deepEqual(checkpoint,completed,'Finish-line checkpoint replay differs')
const result=summarizeCoupled2DResearchV3(completed)
assert.equal(result.stageFinished,true)
assert.equal(result.finish.length,8)
assert.deepEqual(result.finish.map(x=>x.rank),[1,2,3,4,5,6,7,8])
assert(result.finish.every(x=>x.finishSeconds>=result.finish[0].finishSeconds&&x.gapSeconds>=0))
assert.deepEqual(initial,initializeCoupled2DResearchV3(input),'Initializer mutated')
assert.throws(()=>initializeCoupled2DResearchV3({...input,riders:input.riders.map(x=>({...x,meters:100}))}),/before stage finish/)
assert.throws(()=>advanceCoupled2DResearchV3({...completed,officialWrites:1},1),/Invalid/)
console.log(JSON.stringify({suite:'Batch43 finish-line and immutable state',status:'PASS',ticks:completed.tick,firstSeconds:result.finish[0].finishSeconds,lastSeconds:result.finish.at(-1).finishSeconds,officialWrites:0,sportingApproval:'NOT_APPROVED'}))

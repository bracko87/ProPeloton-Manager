import assert from 'node:assert/strict'
import {initializeCoupled2DResearchV3,advanceCoupled2DResearchV3,coupled2DTimingV3,shouldPreparePass2DV3} from './coupled2DMicroV3.mjs'
assert.deepEqual(coupled2DTimingV3(10,'legacy'),{reactionTicks:2,steeringTicks:3,blockedTicks:2,maxSpeedChangeMps:.9})
assert.deepEqual(coupled2DTimingV3(10,'seconds_normalized'),coupled2DTimingV3(10,'legacy'))
assert.deepEqual(coupled2DTimingV3(5,'seconds_normalized'),{reactionTicks:4,steeringTicks:6,blockedTicks:4,maxSpeedChangeMps:.45})
assert.equal(shouldPreparePass2DV3({riderId:'a',finishSeconds:null,blockedStreak:3,reservation:null},[],{},'blocked_2',4),false)
assert.equal(shouldPreparePass2DV3({riderId:'a',finishSeconds:null,blockedStreak:4,reservation:null},[],{},'blocked_2',4),true)
assert.throws(()=>coupled2DTimingV3(7,'seconds_normalized'),/supports 5s and 10s/)
const riders=Array.from({length:8},(_,i)=>({riderId:'r'+i,meters:100-Math.floor(i/4)*2,lane:i%4,speedMps:0,cpWatts:220+i,wPrimeJoules:16000,tactic:'tempo'}))
const base={riders,route:[{lengthKm:3,gradePercent:0}],capacity:3,allowSteering:true,quality:'synthetic_research'}
const control=initializeCoupled2DResearchV3({...base,dt:10})
const legacy=initializeCoupled2DResearchV3({...base,dt:10,experimentalTimingPolicy:'legacy'})
assert.deepEqual(control,legacy,'Legacy default changed serialized state')
assert.deepEqual(advanceCoupled2DResearchV3(control,18),advanceCoupled2DResearchV3(legacy,18),'Legacy default changed motion')
const normalizedTen=initializeCoupled2DResearchV3({...base,dt:10,experimentalTimingPolicy:'seconds_normalized'})
const normalizedTenMotion=advanceCoupled2DResearchV3(normalizedTen,18)
assert.deepEqual(normalizedTenMotion.riders,advanceCoupled2DResearchV3(control,18).riders,'10s normalized motion must equal legacy')
assert.deepEqual(normalizedTenMotion.finish,advanceCoupled2DResearchV3(control,18).finish)
const normalizedFive=initializeCoupled2DResearchV3({...base,dt:5,experimentalTimingPolicy:'seconds_normalized'})
assert.equal(normalizedFive.input.experimentalTimingPolicy,'seconds_normalized')
let half=advanceCoupled2DResearchV3(normalizedFive,9)
const resume=advanceCoupled2DResearchV3(JSON.parse(JSON.stringify(half)),9)
assert.deepEqual(resume,advanceCoupled2DResearchV3(normalizedFive,18))
assert(normalizedTenMotion.riders.every(r=>r.energy.remainingWPrimeJoules>=0))
assert(resume.riders.every(r=>r.energy.remainingWPrimeJoules>=0))
assert.throws(()=>initializeCoupled2DResearchV3({...base,dt:7,experimentalTimingPolicy:'seconds_normalized'}),/Invalid/)
assert.throws(()=>initializeCoupled2DResearchV3({...base,experimentalTimingPolicy:'invalid'}),/Invalid/)
console.log(JSON.stringify({suite:'A2 time-normalized acceleration, reaction and steering',status:'PASS',dt10BaselineExact:true,dt5CheckpointExact:true,officialWrites:0,sportingApproval:'NOT_APPROVED'}))

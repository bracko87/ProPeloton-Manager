import assert from 'node:assert/strict'
import {planCooperativePursuitV3} from '../../src/race-engine-v3/cooperativePursuitV3.ts'
const base=[{riderId:'escaped',meters:1000,action:'attack'},...Array.from({length:20},(_,i)=>({riderId:'pack'+i,meters:600-i*1.5,action:i<3?'chase':'follow'}))].map(r=>({...r,energy:.8,sustainableMps:11.8}))
const all=planCooperativePursuitV3(base,10.5)
assert.equal(all.length,2)
assert.equal(all[0].paceGainMps,0,'Escaped frontmost rider must not phantom chase')
assert(all[1].paceGainMps>0)
assert.equal(all[1].workingRiderIds.length,3)
assert(all[1].targetMps<=11.8*1.02,'Pursuit cannot exceed contributors sustainable power')
assert(all[1].workingRiderIds.every(id=>all[1].workPerSecond[id]>0),'All contributors must pay real energy')
const none=planCooperativePursuitV3(base.map(r=>({...r,action:'follow'})),10.5)
assert.equal(none[1].paceGainMps,0,'Without ordered chasing there is no magically accelerated peloton')
const one=planCooperativePursuitV3(base.map(r=>({...r,action:r.riderId==='pack0'?'chase':'follow'})),10.5)
assert(one[1].paceGainMps<all[1].paceGainMps,'Multiple helpers should cooperate')
const tired=planCooperativePursuitV3(base.map(r=>({...r,energy:.15})),10.5)
assert.equal(tired[1].paceGainMps,0,'Exhausted riders cannot contribute to a powered chase')
const close=planCooperativePursuitV3(base.map(r=>r.riderId==='escaped'?{...r,meters:615}:r),10.5)
assert.equal(close.every(p=>p.paceGainMps===0),true,'No active escape gap means no chase boost')
const reversed=planCooperativePursuitV3([...base].reverse(),10.5)
assert.deepEqual(reversed,all,'Group decisions must not depend on input array order')
assert.throws(()=>planCooperativePursuitV3([...base,base[0]],10.5))
assert.throws(()=>planCooperativePursuitV3(base,-1))
console.log('PASS genuine group-led chase needs a physical gap, costs energy, scales by contributors, respects rider limits')

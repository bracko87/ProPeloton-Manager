import assert from 'node:assert/strict'
import {initializeSubtickEventObserverV3 as start,advanceSubtickEventObserverV3 as advance,affineStrictCrossingFractionV3 as cross,affineLaneEntryFractionV3 as lane,classifySubtickOrderV3 as classify} from './a2SubtickEventObserverV3.mjs'
assert.equal(cross(-5,5),.5)
assert.equal(cross(-5,-2),null)
assert.equal(cross(5,-5),null)
assert.equal(lane(1,0),.5)
assert.equal(lane(1,.75),null)
const r=(riderId,meters,y)=>({riderId,meters,y})
const before=[r('rear',100,0),r('lead',105,1),r('extra2',140,1),r('extra3',160,1)]
const end=(rear,extra2)=>[r('rear',rear,0),r('lead',115,1),r('extra2',150,extra2),r('extra3',170,.8)]
const make=(rear,extra2)=>advance(start({claimantIds:['extra3','extra2']}),before,end(rear,extra2),10)
const earlier=make(120,.4)
assert.equal(earlier.passEvents[0].fraction,.5)
assert.equal(earlier.laneCompletions.extra2.fraction,.833333333)
assert.equal(classify(earlier,'extra2').order,'PASS_BEFORE_LANE_COMPLETION')
assert.equal(classify(make(116,0),'extra2').order,'PASS_AFTER_LANE_COMPLETION')
assert.equal(classify(make(120,0),'extra2').order,'SIMULTANEOUS_OR_NUMERICALLY_UNRESOLVED')
assert.equal(classify(make(109,0),'extra2').order,'UNOBSERVED')
const later=[r('rear',122,0),r('lead',119,1),r('extra2',154,.9),r('extra3',174,.3)]
const restored=advance(JSON.parse(JSON.stringify(earlier)),end(120,.4),later,20)
const direct=advance(earlier,end(120,.4),later,20)
assert.deepEqual(restored,direct)
assert.equal(direct.directionReversals.extra2,1)
assert.equal(direct.laneCompletions.extra3.tick,2)
const perm=advance(start({claimantIds:['extra2','extra3']}),before.slice().reverse(),end(120,.4).slice().reverse(),10)
assert.deepEqual(perm,earlier)
assert.equal(direct.officialWrites,0)
assert.equal(direct.sportingApproval,'NOT_APPROVED')
assert.throws(()=>start({dt:0}),/Invalid/)
console.log(JSON.stringify({suite:'A2 affine swept-path within-tick event timing',status:'PASS',before:true,after:true,simultaneous:true,reversal:true,checkpoint:true,orderInvariant:true,officialWrites:0}))

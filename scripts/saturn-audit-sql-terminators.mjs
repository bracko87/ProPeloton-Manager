/**
 * Syntax-only check of historically imported SQL migrations.
 * A stand-alone closing dollar quote without a semicolon is not a complete
 * CREATE FUNCTION or DO statement. This script does not modify any file.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const folder = fileURLToPath(new URL('../supabase/migrations/', import.meta.url))
const suspicious = []
let files = 0

for (const file of readdirSync(folder).filter(name => name.endsWith('.sql')).sort()) {
  files++
  const source = readFileSync(folder + '/' + file, 'utf8')
  const lines = source.split('\n')
  // Exact stand-alone closing delimiters generated by the original schema
  // dump are usually preceded by a PL/pgSQL END statement and MUST have ';'.
  for (let index = 0; index < lines.length; index++) {
    if (/^\s*\$(?:function|body|proc)\$\s*$/i.test(lines[index])) {
      suspicious.push(file + ':' + (index + 1) + ': dollar-quote terminator lacks semicolon')
    }
  }
}
if (suspicious.length) {
  console.error('Found ' + suspicious.length + ' possibly unterminated SQL functions across ' + files + ' migration files:')
  for (const item of suspicious) console.error(item)
  process.exitCode = 1
} else {
  console.log('PASS: ' + files + ' migration files have no stand-alone unterminated function delimiters.')
}
